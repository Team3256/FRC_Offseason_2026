#!/usr/bin/env python3
"""Generate robot graph definitions from robot.mayhem.json. No solver/Node required.

Supports Mayhem pose/action/custom/finish nodes, during actions, path events,
rotation markers, and typed nested conditions. Unknown forms fail the build.
"""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
Q = lambda x: json.dumps(x, ensure_ascii=True)
def num(x):
    if isinstance(x, bool): return str(x).lower()
    return str(float(x))
def value(x):
    if isinstance(x, str): return 'std::string_view{' + Q(x) + '}'
    if isinstance(x, bool): return num(x)
    return 'double{' + num(x) + '}'
def condition(c):
    k = c['kind']
    if k == 'always': return 'std::optional<bool>{true}'
    if k == 'signal':
        op = {'eq':'Eq','gt':'Gt','lt':'Lt'}[c['op']]
        return f'mayhem::Compare(h.Signal({Q(c["key"])}),mayhem::CompareOp::{op},mayhem::SignalValue{{{value(c["value"])}}})'
    if k == 'not': return 'mayhem::Not(' + condition(c['condition']) + ')'
    return 'mayhem::' + {'all':'All','any':'Any'}[k] + '({' + ','.join(map(condition,c['conditions'])) + '})'
def export(d):
    out=['// Generated by tools/mayhem/export.py. Edit robot.mayhem.json, then regenerate.', '#pragma once', '// clang-format off', '#include <array>', '#include <string>', '#include "mayhem/auto_runner.hpp"', 'namespace robot_mayhem {']
    defaults=dict(maxVelocity=4.5,maxAcceleration=12,maxAngularVelocity=12.566370614359172,maxAngularAcceleration=26.17993877991494,translationKp=5,rotationKp=3,handoffRadius=.45,crossTrackKp=2,minVelocity=0)
    def graph(r, ns):
        out.append('namespace '+ns+' {')
        nodes=r['nodes']; transitions=[t | {'id':r['id']+'/'+t['id']} for t in r['transitions']] if ns.startswith('auto_') else r['transitions']; ids={n['id']:i for i,n in enumerate(nodes)}
        assert r['initial'] in ids and len(ids)==len(nodes)
        for i,t in enumerate(transitions):
            assert t['from'] in ids and t['to'] in ids
            out.append(f'inline bool guard_{i}([[maybe_unused]] const mayhem::RobotHooks& h) {{ return ({condition(t["condition"])}).value_or(false); }}')
        for i,n in enumerate(nodes):
            markers=n.get('goal',{}).get('markers',[])
            entries=[]
            for m in markers:
                assert m['kind'] in ('event','rotation')
                entries.append('{mayhem::MarkerKind::'+('Event' if m['kind']=='event' else 'Rotation')+','+num(m['t'])+','+num(m.get('heading',0))+','+Q(m.get('key',''))+','+num(m.get('profiled',True))+'}')
            out.append(f'inline constexpr std::array<mayhem::PathMarker,{len(entries)}> markers_{i} = {{{{'+','.join(entries)+'}};')
            out.append(f'inline constexpr std::array<std::string_view,{len(n.get("during",[]))}> during_{i} = {{'+','.join(map(Q,n.get('during',[])))+'};')
        out.append(f'inline constexpr std::array<mayhem::AutoNode,{len(nodes)}> nodes = {{{{')
        for i,n in enumerate(nodes):
            g=n.get('goal'); goal='{}'
            if g:
                pose='{'+','.join(num(g[k]) for k in ('x','y','heading'))+'}'
                fields=[num(g.get(k,default)) for k,default in [('translationTolerance',.03),('rotationTolerance',.035),('velocityTolerance',.15),('settleTime',0),('handoffRadius',0)]]
                heading={'fixed':'Fixed','pointAt':'PointAt','motion':'Motion','free':'Free'}[g.get('headingMode','fixed')]
                fields+=['mayhem::HeadingMode::'+heading,num(g.get('aimX',0)),num(g.get('aimY',0)),num(g.get('stop',False)),num(g.get('projectedHandoff',False)),num(g.get('profiled',True)),f'markers_{i}.data()',f'markers_{i}.size()']
                goal='{'+pose+','+','.join(fields)+'}'
            inherited=defaults | d['robot']['constraints'] | r.get('constraints',{})
            generated=dict(n.get('generatedConstraints',{}))
            if 'maxVelocity' in generated: generated['maxVelocity']=min(inherited['maxVelocity'],generated['maxVelocity'])
            c=inherited | generated | n.get('constraints',{})
            edges=[t for t in transitions if t['from']==n['id']]
            nxt=ids[edges[0]['to']] if len(edges)==1 and edges[0]['condition']['kind']=='always' else -1
            intermediate=bool(g and not g.get('stop',False) and nxt>=0 and nodes[nxt]['kind']=='pose')
            kind={'pose':'Pose','action':'Action','custom':'Custom','finish':'Finish'}[n['kind']]
            out.append('{'+','.join([Q(n['id']),'mayhem::NodeKind::'+kind,goal,num(n['timeout']),Q(n.get('action','')),'{'+','.join(num(c[k]) for k in defaults)+'}',f'during_{i}.data()',f'during_{i}.size()',str(nxt),num(intermediate)])+'},')
        out.append('}};')
        out.append(f'inline constexpr std::array<mayhem::AutoTransition,{len(transitions)}> transitions = {{{{')
        for i,t in enumerate(transitions): out.append('{'+','.join([Q(t['id']),Q(t['from']),Q(t['to']),f'guard_{i}'])+'},')
        out.append('}};')
        out.append('inline constexpr mayhem::RoutineView routine{'+','.join([Q(r['id']),Q(r['initial']),'nodes.data()','nodes.size()','transitions.data()','transitions.size()'])+'};')
        out.append('}')
    for i,r in enumerate(d['routines']): graph(r,f'auto_{i}')
    for m in d['extensions']['machines']:
        graph(dict(id=m['id'],initial=m['initial'],nodes=[dict(id=s['id'],kind='custom',action='state',timeout=1e9) for s in m['states']],transitions=m['transitions']),m['id'])
    def manifest(name, obj):
        text=json.dumps(obj,separators=(',',':'))
        out.append('inline const std::string '+name+' = [] { std::string text; text.reserve('+str(len(text))+');')
        for i in range(0,len(text),4000): out.append('text += '+Q(text[i:i+4000])+';')
        out.append('return text; }();')
    for m in d['extensions']['machines']:
        manifest(m['id']+'Manifest',m)
    # One stable machine includes all autonomous nodes; IDs already identify path/part.
    states={n['id']:{'id':n['id'],'name':n['name'],'source':n.get('source','robot.mayhem.json')} for r in d['routines'] for n in r['nodes']}
    edges=[]
    for i,r in enumerate(d['routines']):
        edges += [t | {'id':r['id']+'/'+t['id']} for t in r['transitions']]
    m=dict(format='mayhem-machine',version=1,id='Autonomous',name='Autonomous',initial=d['routines'][0]['initial'],states=list(states.values()),transitions=edges,inputs=d['signals'],stateChannel='/Mayhem/States/Autonomous/state')
    manifest('AutonomousManifest',m)
    out.append('struct AutoDefinition { std::string_view name; mayhem::RoutineView routine; mayhem::Pose start; };')
    out.append(f'inline constexpr std::array<AutoDefinition,{len(d["routines"])}> autos = {{{{')
    for i,r in enumerate(d['routines']):
        s=r.get('start',d['robot']['start'])
        out.append('{'+Q(r['name'])+f',auto_{i}::routine,{{'+','.join(num(s[k]) for k in ('x','y','heading'))+'}},')
    out+=['}};', '}']
    return '\n'.join(out)+'\n// clang-format on\n'
def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--check',action='store_true'); a=ap.parse_args()
    text=export(json.loads((ROOT/'robot.mayhem.json').read_text()))
    path=ROOT/'src/main/include/commands/MayhemProject.h'
    if a.check:
        if not path.exists() or path.read_text()!=text: raise SystemExit('MayhemProject.h is stale. Run python3 tools/mayhem/export.py')
    else: path.write_text(text)
if __name__=='__main__': main()
